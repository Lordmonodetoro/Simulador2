    # SOLVER ITERATIVO (Garantiza convergencia térmica y másica)
    # ====================================================================
    def simular(self, tol=1e-4, max_iter=50):
        # 1. Ejecución lineal inicial (Módulos sin dependencias cíclicas hacia atrás)
        m1 = self.mod_1_difusiones()
        m2 = self.mod_2_calentamiento_crudo(m1)
        
        # 2. Inicialización de diccionarios de estado
        m3_prev, m4_prev, m5_prev, m6_prev, m7_prev, m8_prev = {}, {}, {}, {}, {}, {}
        vapor_total_prev = 0.0
        
        # 3. BUCLE ITERATIVO
        for iteracion in range(max_iter):
            m3 = self.mod_3_depuracion(m1, m2, m8_prev)
            m4 = self.mod_4_calentamiento_jugo_fino(m3)
            
            m7_pre = self.mod_7_refundicion(m5_prev, m3, m6_prev)
            m6 = self.mod_6_casa_cocimiento(m1, m7_pre)
            m7 = self.mod_7_refundicion(m5_prev, m3, m6)
            
            m5 = self.mod_5_evaporacion(m4, m3, m6, m7, m1, m2)
            m8 = self.mod_8_condensados_agua(m5, m6, m4, m3, m1, m2, m7)
            
            # Evaluación del Error (Usando la demanda total de la Estación de Evaporación)
            demanda_vapores = (
                m5.get('OUT_M5_Demanda_V1_Total_th', 0) +
                m5.get('OUT_M5_Demanda_V2_Total_th', 0) +
                m5.get('OUT_M5_Demanda_V3_Total_th', 0) +
                m5.get('OUT_M5_Demanda_V4_Total_th', 0) +
                m5.get('OUT_M5_Demanda_V5_Total_th', 0) +
                m5.get('OUT_M5_Demanda_V6_Total_th', 0)
            )
            
            if demanda_vapores > 0:
                error_relativo = abs((demanda_vapores - vapor_total_prev) / demanda_vapores)
            else:
                error_relativo = 1.0 
                
            # Criterio de parada
            if error_relativo < tol and iteracion > 2:
                break
                
            # Actualización de estados
            m3_prev, m4_prev, m5_prev, m6_prev, m7_prev, m8_prev = m3, m4, m5, m6, m7, m8
            vapor_total_prev = demanda_vapores

        # 4. Módulo final aislado (Energía)
        m9 = self.mod_9_energia(m1, m4, m5, m6)

        # 5. Formateo y Limpieza Decimal
        for modulo in [m1, m2, m3, m4, m5, m6, m7, m8, m9]:
            for k, v in modulo.items():
                if isinstance(v, (int, float, np.floating)):
                    modulo[k] = round(float(v), 2)

        self.resultados = {'M1': m1, 'M2': m2, 'M3': m3, 'M4': m4, 'M5': m5, 'M6': m6, 'M7': m7, 'M8': m8, 'M9': m9}
        return self.resultados

