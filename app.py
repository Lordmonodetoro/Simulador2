        ms_corefin = azucar_corefin
        pol_corefin = azucar_corefin * 0.992

        flujo_etapa_1 = flujo_jugo_entrada + lodos_2do + lechada_preencalado
        flujo_etapa_2 = flujo_etapa_1 + azucar_corefin + lechada_encalado_frio

