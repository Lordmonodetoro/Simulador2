        t_out_4 = float(c['OP_Calent_4_TempSalida_C'])
        out['OUT_Calentador4_Vapor_th'] = (flujo_etapa_2 * cp_jugo * max(0.0, t_out_4 - t_out_3b)) / self.cat_vap['Vapor_6toEfecto']['entalpia']
        t_out_56 = float(c['OP_Calent_56_TempSalida_C'])
