        out['OUT_Calentador9_Vapor_th'] = (flujo_etapa_4 * cp_jugo * max(0.0, t_out_no9 - t_out_1ra_filt)) / self.cat_vap['Vapor_3erEfecto']['entalpia']
        t_out_2da_carb = t_out_no9 - float(c['OP_Enfriamiento_2daCarb_C'])

