    def simular(self):
        # 1. Pasada Preliminar (Ruptura de referencias circulares)
        m1 = self.mod_1_difusiones()
        m2 = self.mod_2_calentamiento_crudo(m1)
        m8_init = {}
        m3_init = self.mod_3_depuracion(m1, m2, m8_init)
        m4_init = self.mod_4_jugo_fino(m3_init)
        m7_init = self.mod_7_refundicion({}, m3_init, {})
        m6_init = self.mod_6_cocimiento(m7_init)
        m5_init = self.mod_5_evaporacion(m4_init, m3_init, m6_init, m7_init, m1, m2)
        m8_pasada1 = self.mod_8_condensados(m5_init, m6_init, m4_init, m3_init, m1, m2, m7_init)

        # 2. Pasada Final (Balances exactos)
        m3 = self.mod_3_depuracion(m1, m2, m8_pasada1)
        m4 = self.mod_4_jugo_fino(m3)
        m6 = self.mod_6_cocimiento(m7_init)
        m7 = self.mod_7_refundicion(m5_init, m3, m6)
        m5 = self.mod_5_evaporacion(m4, m3, m6, m7, m1, m2)
        m8 = self.mod_8_condensados(m5, m6, m4, m3, m1, m2, m7)
        m9 = self.mod_9_energia(m1, m4, m5, m6)

        # Redondear y guardar
        for modulo in [m1, m2, m3, m4, m5, m6, m7, m8, m9]:
            for k, v in modulo.items():
                if isinstance(v, (int, float)): modulo[k] = round(v, 2)
                elif isinstance(v, dict):
                    for k2, v2 in v.items():
                        if isinstance(v2, (int, float)): v[k2] = round(v2, 2)

        self.resultados = {'M1': m1, 'M2': m2, 'M3': m3, 'M4': m4, 'M5': m5, 'M6': m6, 'M7': m7, 'M8': m8, 'M9': m9}
        return self.resultados

